test('infinite canvas drags groups and nodes, pans, zooms, edits connections and restores layout',async()=>{
  const frame=plugin(),canvas=frame.locator('#canvas')
  await frame.locator('[data-stage="0"]').click()
  const group=frame.locator('#stage-0'),handle=group.getByRole('button',{name:'移动分组 数据收集与整理',exact:true})
  const position=()=>group.evaluate(el=>({x:parseFloat(el.style.left),y:parseFloat(el.style.top)}))
  const before=await position(),zoom=Number(await canvas.getAttribute('data-zoom'))
  const headerBox=await handle.boundingBox();if(!headerBox)throw new Error('group header hidden')
  await page.mouse.move(headerBox.x+headerBox.width/2,headerBox.y+headerBox.height/2);await page.mouse.down();await page.mouse.move(headerBox.x+headerBox.width/2+50,headerBox.y+headerBox.height/2+25,{steps:8});await page.mouse.up()
  await expect.poll(async()=>Math.round((await position()).x-before.x)).toBe(Math.round(50/zoom))
  await frame.locator('[data-stage="0"]').click()
  const market=frame.locator('.canvas-node[data-canvas-node="market"]'),card=market.locator('.node')
  const oldX=await market.evaluate(el=>parseFloat(el.style.left)),cardBox=await card.boundingBox();if(!cardBox)throw new Error('node hidden')
  await page.mouse.move(cardBox.x+cardBox.width/2,cardBox.y+30);await page.mouse.down();await page.mouse.move(cardBox.x+cardBox.width/2+30,cardBox.y+50,{steps:8});await page.mouse.up()
  await expect.poll(()=>market.evaluate(el=>parseFloat(el.style.left))).toBeGreaterThan(oldX)
  await expect(frame.locator('#detail')).toBeHidden()
  await card.locator('.node-title').dblclick()
  await expect(frame.getByRole('heading',{name:'市场与趋势',exact:true})).toBeVisible()
  await frame.getByRole('button',{name:'关闭节点详情',exact:true}).click()
  await frame.getByRole('button',{name:'市场与趋势 输出端点',exact:true}).click()
  await frame.getByRole('button',{name:'竞品与价格 输入端点',exact:true}).click()
  const edge=frame.getByRole('button',{name:'市场与趋势 → 竞品与价格 依赖连线',exact:true})
  await expect(edge).toHaveCount(1)
  await edge.focus();await page.keyboard.press('Enter')
  await frame.getByRole('button',{name:'删除连线',exact:true}).click()
  await expect(edge).toHaveCount(0)
  const z1=Number(await canvas.getAttribute('data-zoom'))
  await frame.getByRole('button',{name:'放大画布',exact:true}).click()
  await expect.poll(async()=>Number(await canvas.getAttribute('data-zoom'))).toBeGreaterThan(z1)
  const z2=Number(await canvas.getAttribute('data-zoom')),canvasBox=await canvas.boundingBox();if(!canvasBox)throw new Error('canvas hidden')
  await page.mouse.move(canvasBox.x+15,canvasBox.y+15)
  await page.keyboard.down('Control');await page.mouse.wheel(0,-50);await page.keyboard.up('Control')
  await expect.poll(async()=>Number(await canvas.getAttribute('data-zoom'))).toBeGreaterThan(z2)
  await canvas.focus();const x1=Number(await canvas.getAttribute('data-pan-x'));await page.keyboard.press('ArrowRight')
  await expect.poll(async()=>Number(await canvas.getAttribute('data-pan-x'))).toBe(x1-60)
  await expect(frame.locator('.layout-status')).toHaveText('布局已保存')
  const finalGroup=await position(),finalNode=await market.evaluate(el=>el.style.left),finalZoom=await canvas.getAttribute('data-zoom'),finalPan=await canvas.getAttribute('data-pan-x')
  await page.getByRole('button',{name:'概览',exact:true}).click();await page.getByRole('button',{name:'选品工作台',exact:true}).click()
  await expect.poll(position).toEqual(finalGroup)
  await expect(market).toHaveCSS('left',finalNode)
  await expect(canvas).toHaveAttribute('data-zoom',finalZoom!)
  await expect(canvas).toHaveAttribute('data-pan-x',finalPan!)
  await frame.getByRole('button',{name:'适应全图',exact:true}).click()
  await page.screenshot({path:test.info().outputPath('infinite-canvas.png')})
})
