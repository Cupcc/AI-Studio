import { existsSync, readFileSync, mkdirSync, mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { _electron as electron, expect, test, type ElectronApplication, type Page } from '@playwright/test'
import { closeTestApp } from './quit'
let dir: string, app: ElectronApplication, page: Page
const appDir=join(__dirname,'..'), plugin=()=>page.frameLocator('iframe[title="工作台页面"]')
async function launch() {
  app=await electron.launch({args:[appDir,`--studio-user-data-dir=${join(dir,'data')}`],cwd:appDir,env:{...process.env,STUDIO_E2E_PROVIDERS:'1'}})
  page=await app.firstWindow();await page.waitForLoadState('domcontentloaded')
}
test.beforeEach(async()=>{
  dir=mkdtempSync(join(tmpdir(),'selection-e2e-'));const project=join(dir,'project');mkdirSync(project)
  await launch();await app.evaluate(({dialog},path)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[path]})},project)
  await page.getByRole('button',{name:'打开本地目录',exact:true}).click()
  await expect(page.getByRole('button',{name:'选品工作台',exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'添加工作台',exact:true}).click()
  await page.getByRole('button',{name:'添加 选品工作台',exact:true}).click()
  await expect(plugin().locator('#run-all')).toBeDisabled()
  await page.getByRole('button',{name:'添加至当前项目',exact:true}).click()
  await expect(plugin().locator('#run-all')).toBeEnabled()
})
test.afterEach(async()=>{await closeTestApp(app,page);rmSync(dir,{recursive:true,force:true})})
async function brief(text:string) {
  await plugin().getByRole('button',{name:'任务要求',exact:true}).click()
  await plugin().getByRole('textbox',{name:'任务目标',exact:true}).fill(text)
  await plugin().getByRole('button',{name:'保存要求',exact:true}).click()
  await expect(plugin().locator('#notice')).toHaveText('任务要求已保存。')
}
async function node(id:string) {
  const stage=id.startsWith('design-')?3:id==='candidates'?2:id==='analysis'?1:0
  await plugin().locator(`[data-stage="${stage}"]`).click()
  await plugin().locator(`[data-canvas-node="${id}"] [data-action="open"]`).click()
}
test('four stages execute, candidates persist, local changes invalidate only matching design, and export works',async()=>{
  await brief('[e2e:selection] 合成选品验证')
  await plugin().getByRole('button',{name:'运行四个流程',exact:true}).click()
  await expect(plugin().locator('#progress')).toHaveText('10 / 10 节点已有最新结果',{timeout:45_000})
  await node('candidates')
  await plugin().locator('[data-select="A"]').check()
  await expect(plugin().locator('[data-select="A"]')).toBeChecked()
  await plugin().locator('[data-select="B"]').check()
  await expect(plugin().locator('[data-select="B"]')).toBeChecked()
  await plugin().locator('[data-edit="B"]').click()
  await plugin().locator('#edit-value').fill('白色哑光陶瓷')
  await plugin().locator('#edit-form').getByRole('button',{name:'保存',exact:true}).click()
  await plugin().getByRole('button',{name:'关闭节点详情',exact:true}).click()
  await expect(plugin().locator('#detail')).toBeHidden()
  await expect(plugin().locator('.node[data-node="design-B"]')).toContainText('需复核更新')
  await expect(plugin().locator('.node[data-node="design-A"]')).toContainText('已有结果')
  await plugin().getByRole('button',{name:'比较入选',exact:true}).click()
  await expect(plugin().locator('#comparison')).toContainText('白色哑光陶瓷')
  await plugin().getByRole('button',{name:'关闭',exact:true}).click()
  const exported=join(dir,'handoff.html')
  await app.evaluate(({ session }, path) => { session.defaultSession.once('will-download', (_event, item) => item.setSavePath(path)) }, exported)
  await plugin().getByRole('button',{name:'导出交接简报',exact:true}).click()
  await expect.poll(()=>existsSync(exported)).toBe(true)
  expect(readFileSync(exported,'utf8')).toContain('白色哑光陶瓷')
  await closeTestApp(app,page);await launch()
  await expect(plugin().locator('#progress')).toHaveText('9 / 10 节点已有最新结果')
  await node('candidates');await expect(plugin().locator('[data-select="B"]')).toBeChecked()
})
